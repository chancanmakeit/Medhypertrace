"""Per-injection-strategy evaluation of the step head on the AEGIS synthetic test split (reply to MAFA a127195).

response_corruption (RC) faults ARE fixed template sentences spliced into the reply
(injection_process.corruption_template), so detecting them is detecting a template; prompt_injection (PI)
faults are generated by the model under a modified prompt (closer to real faults, but PI steps are often
EMPTY in llm_debate / clinical_agent5). Nothing is deleted from the data (unlike round 9).

Model: MedHyperTrace default config trained on the FULL fixed train split (the main-table setting), seeds 0-2.
Test subsets (fixed test split):
  all             every test trajectory
  earliest_PI     the earliest injected step (the step label) was a prompt_injection
  earliest_RC     ... a response_corruption
  PI_only         every injection in the trajectory is prompt_injection
Baselines on the same subsets: first_step; template (first step containing a train-learned template line);
empty (first step with < 5 chars); anomaly (first step that is template OR empty); each falls back to step 1.
Reports k/n with Wilson 95% CI. Usage: python analysis/strategy_split_eval.py [framework ...]
"""
import json
import math
import os
import random
import sys

_r = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, _r)
import numpy as np  # noqa: E402
import torch  # noqa: E402

from analysis.artifact_audit import has_tpl, learn_templates  # noqa: E402
from common.data import load_jsonl  # noqa: E402
from common.paths import FILES, SPLITS_JSON  # noqa: E402
from ours import train_hgnn as T  # noqa: E402

SEEDS = [0, 1, 2]


def wilson(k, n, z=1.96):
    if not n:
        return None
    p = k / n; d = 1 + z * z / n; c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return [round(c - h, 3), round(c + h, 3)]


def acting(t):
    return [s for s in t.steps if not s.is_input]


def subset_of(t):
    app = [s for s in t.steps if s.injection_applied]
    e = min(app, key=lambda s: s.turn).injection_strategy
    sts = {s.injection_strategy for s in app}
    out = ["all", "earliest_PI" if e == "prompt_injection" else "earliest_RC"]
    if sts == {"prompt_injection"}:
        out.append("PI_only")
    return out


def first_where(t, pred):
    a = acting(t)
    return next((s.turn for s in a if pred(s)), a[0].turn)


@torch.no_grad()
def model_preds(model, samples, fd, trajs):
    model.eval()
    out = []
    for s, t in zip(samples, trajs):
        b = T.collate([s], fd)
        sl, _, _ = model(b["feats"], b["type_ids"], b["type_slices"], b["incidence"])
        sid = s["step_ids"][int(torch.argmax(sl))]
        out.append(int(sid[1:]))
    return out


def main(fws):
    sp = json.load(open(SPLITS_JSON))
    args = T.get_args(["x"])
    report = {}
    for fw in fws:
        trajs = load_jsonl(FILES[fw])
        tr_ids, te_ids = set(sp[fw]["train_task_ids"]), set(sp[fw]["test_task_ids"])
        train = [t for t in trajs if t.id in tr_ids]
        test = [t for t in trajs if t.id in te_ids and t.labels.earliest_error_turn is not None]
        tpl = learn_templates(train)
        empty = lambda s: len(s.content.strip()) < 5  # noqa: E731
        preds = {"first_step": [acting(t)[0].turn for t in test],
                 "template": [first_where(t, lambda s: has_tpl(s, tpl)) for t in test],
                 "empty": [first_where(t, empty) for t in test],
                 "anomaly": [first_where(t, lambda s: has_tpl(s, tpl) or empty(s)) for t in test]}
        fz = T.make_featurizer("tfidf", train, None)
        samples = [T.build_sample(t, fz, args.struct, None) for t in test]
        for sd in SEEDS:
            random.seed(sd); np.random.seed(sd); torch.manual_seed(sd)
            tr, va = T.split_val(train)
            model, _, fd = T.train_model(tr, va, fz, args)
            preds[f"mht_seed{sd}"] = model_preds(model, samples, fd, test)
            print(f"  [{fw}] seed {sd} done", flush=True)
        gold = [t.labels.earliest_error_turn for t in test]
        subs = [subset_of(t) for t in test]
        res = {}
        for sub in ["all", "earliest_PI", "earliest_RC", "PI_only"]:
            idx = [i for i, s in enumerate(subs) if sub in s]
            row = {"n": len(idx)}
            for name, p in preds.items():
                k = sum(p[i] == gold[i] for i in idx)
                row[name] = {"k": k, "rate": round(k / len(idx), 3) if idx else None, "ci95": wilson(k, len(idx))}
            m = [row[f"mht_seed{s}"]["rate"] for s in SEEDS if row[f"mht_seed{s}"]["rate"] is not None]
            row["mht_mean"] = round(sum(m) / len(m), 3) if m else None
            res[sub] = row
        report[fw] = res
        print(f"== {fw}", flush=True)
        for sub, row in res.items():
            if not row["n"]:
                continue
            fmt = lambda r: f"{r['k']}/{row['n']}={r['rate']:.2f}"  # noqa: E731
            print(f"  {sub:12s} n={row['n']:4d} first {fmt(row['first_step'])}  template {fmt(row['template'])}  "
                  f"empty {fmt(row['empty'])}  anomaly {fmt(row['anomaly'])}  MHT mean {row['mht_mean']:.3f} "
                  f"(seeds {', '.join(str(row[f'mht_seed{s}']['rate']) for s in SEEDS)})", flush=True)
    out = os.path.join(_r, "analysis", "strategy_split_eval.json")
    json.dump(report, open(out, "w"), indent=1)
    print("wrote", out)


if __name__ == "__main__":
    main(sys.argv[1:] or list(FILES))
